

"""Простий веселий скрипт без попереджень редактора."""

import random
import time





def main():
    name = input("Як тебе звати? ") or "друже"
    print(f"\nПривіт, {name}! 👋")

    vibes = [
        "Ти впораєшся! ✨",
        "Сьогодні буде класно! 🚀",
        "Малі перемоги — це вже успіх! 💪",
        "Кодуй із задоволенням! 😄",
    ]

    jokes = [
        "Чому програміст любить Python? Бо він завжди в темі.",
        "Програміст відкрив холодильник: там теж був код — тільки холодний.",
        "Що каже комп'ютер після важкого дня? Поки!",
    ]

    for _ in range(3):
        print(random.choice(vibes))
        time.sleep(0.5)

    print("\nЖарт на добрий настрій:")
    print(random.choice(jokes))
    print("\nКодуй із радістю! 😎")


if __name__ == "__main__":
    main()